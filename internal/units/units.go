// Package units turns cyac's conf files into systemd units. It is the
// whole of what cyac-generator does, kept pure so it can be tested by
// comparing output: no kernel, no socket, no network.
//
// Every object becomes one unit named <primitive>@<name>, with the
// dependencies that make systemd bring things up in order and take them
// down in reverse:
//
//	cygateway@g   oneshot: the gateway netns and its uplink
//	cynetwork@n   oneshot: the bridge; BindsTo its gateway
//	cydns@n       socket-activated DNS on the network's .2; PartOf the network
//	cyservice@s   the service container; BindsTo its gateway and every
//	              network that attaches it
//	cybox@b       the box; BindsTo its network, Wants the network's services
//
// Gateways and networks stop when nothing needs them any more, so their
// interfaces never outlive the boxes on them.
package units

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/containmentzone/cyacrt/internal/conf"
)

// Paths says where the binaries and the conf dir are, as the units should
// refer to them.
type Paths struct {
	Cyac      string // the cyac binary
	Generator string // this generator, for -check
	ConfDir   string
}

// Output is what the generator writes: unit files by name, and symlinks
// (path relative to the output dir, pointing at a unit in it).
type Output struct {
	Files    map[string]string
	Symlinks map[string]string
}

// Target is the unit that starts every Autostart box.
const Target = "cyac.target"

// Generate produces the units for c. Each problem becomes a unit that
// fails with its error when started, in place of the object's real unit,
// so a broken file shows up in systemctl status instead of vanishing.
func Generate(c *conf.Config, probs []conf.Problem, p Paths) Output {
	out := Output{Files: map[string]string{}, Symlinks: map[string]string{}}
	out.Files[Target] = "[Unit]\nDescription=cyac boxes and services\n"
	out.Symlinks["multi-user.target.wants/"+Target] = "../" + Target

	for _, name := range conf.Sorted(c.Gateways) {
		out.Files[Name(conf.KindGateway, name)] = gateway(c.Gateways[name], p)
	}
	for _, name := range conf.Sorted(c.Networks) {
		n := c.Networks[name]
		out.Files[Name(conf.KindNetwork, name)] = network(n, p)
		out.Files["cydns@"+name+".socket"] = dnsSocket(n, p)
		out.Files["cydns@"+name+".service"] = dnsService(n, p)
	}
	for _, name := range conf.Sorted(c.Services) {
		out.Files[Name(conf.KindService, name)] = service(c, c.Services[name], p)
	}
	for _, name := range conf.Sorted(c.Boxes) {
		b := c.Boxes[name]
		out.Files[Name(conf.KindBox, name)] = box(c, b, p)
		if b.Autostart {
			out.Symlinks[Target+".wants/"+Name(conf.KindBox, name)] = "../" + Name(conf.KindBox, name)
		}
	}
	for _, pr := range probs {
		out.Files[Name(pr.Kind, pr.Name)] = broken(pr, p)
	}
	return out
}

// Name is the unit name for an object.
func Name(kind, name string) string { return kind + "@" + name + ".service" }

// unit is a unit file being written, section by section, in a fixed
// order so the output is stable.
type unit struct{ b strings.Builder }

func (u *unit) section(name string) { fmt.Fprintf(&u.b, "\n[%s]\n", name) }
func (u *unit) set(key, value string) {
	if value != "" {
		fmt.Fprintf(&u.b, "%s=%s\n", key, value)
	}
}

// after adds both a dependency of type dep and the ordering, which
// systemd keeps separate.
func (u *unit) after(dep string, units ...string) {
	if len(units) > 0 {
		u.set(dep, strings.Join(units, " "))
		u.set("After", strings.Join(units, " "))
	}
}

func header(kind, name string, p Paths, desc string) *unit {
	u := &unit{}
	fmt.Fprintf(&u.b, "# Generated by cyac-generator from %s. Edit that file, not this one.\n", conf.Path(p.ConfDir, kind, name))
	u.section("Unit")
	u.set("Description", desc)
	u.set("SourcePath", conf.Path(p.ConfDir, kind, name))
	u.set("PartOf", Target)
	return u
}

// run is the command line for one stage of an object's lifecycle.
func run(p Paths, verb, kind, name string) string {
	return fmt.Sprintf("%s run %s %s %s", p.Cyac, verb, kind, name)
}

// oneshot is the service section shared by gateways and networks: start
// creates the kernel objects, stop removes them.
func oneshot(u *unit, p Paths, kind, name string) string {
	u.set("StopWhenUnneeded", "yes")
	u.section("Service")
	u.set("Type", "oneshot")
	u.set("RemainAfterExit", "yes")
	u.set("ExecStart", run(p, "start", kind, name))
	u.set("ExecStop", run(p, "stop", kind, name))
	return u.b.String()
}

func gateway(g *conf.Gateway, p Paths) string {
	u := header(conf.KindGateway, g.Name, p, "cyac gateway "+g.Name+" ("+g.Kind+")")
	return oneshot(u, p, conf.KindGateway, g.Name)
}

func network(n *conf.Network, p Paths) string {
	u := header(conf.KindNetwork, n.Name, p, "cyac network "+n.Name+" ("+n.Prefix().String()+")")
	if n.Gateway != "" {
		u.after("BindsTo", Name(conf.KindGateway, n.Gateway))
	}
	u.set("Wants", "cydns@"+n.Name+".socket")
	return oneshot(u, p, conf.KindNetwork, n.Name)
}

// The DNS units are PartOf the network rather than BindsTo it: they stop
// with it, but don't count as needing it, so the network can still stop
// when its last box does.
func dnsSocket(n *conf.Network, p Paths) string {
	u := dnsHeader(n, p)
	u.section("Socket")
	addr := n.Host().String() + ":53"
	u.set("ListenDatagram", addr)
	u.set("ListenStream", addr)
	// The socket may start before the bridge has its address.
	u.set("FreeBind", "yes")
	return u.b.String()
}

func dnsService(n *conf.Network, p Paths) string {
	u := dnsHeader(n, p)
	u.section("Service")
	u.set("ExecStart", p.Cyac+" dns "+n.Name)
	return u.b.String()
}

func dnsHeader(n *conf.Network, p Paths) *unit {
	u := &unit{}
	fmt.Fprintf(&u.b, "# Generated by cyac-generator from %s. Edit that file, not this one.\n", conf.Path(p.ConfDir, conf.KindNetwork, n.Name))
	u.section("Unit")
	u.set("Description", "cyac DNS for network "+n.Name)
	u.set("PartOf", Name(conf.KindNetwork, n.Name))
	u.set("After", Name(conf.KindNetwork, n.Name))
	return u
}

// workload is the service section shared by boxes and services: start
// runs the workload in the foreground, and stop cleans up after it
// however it ended.
func workload(u *unit, p Paths, kind, name string, creds []conf.Secret) string {
	u.section("Service")
	u.set("Type", "simple")
	for _, s := range creds {
		u.set("LoadCredential", s.Name+":"+s.Path)
	}
	u.set("ExecStart", run(p, "start", kind, name))
	u.set("ExecStopPost", run(p, "stop", kind, name))
	return u.b.String()
}

func service(c *conf.Config, s *conf.Service, p Paths) string {
	u := header(conf.KindService, s.Name, p, "cyac service "+s.Name)
	deps := []string{Name(conf.KindGateway, s.Gateway)}
	for _, n := range c.AttachedBy(s.Name) {
		deps = append(deps, Name(conf.KindNetwork, n))
	}
	u.after("BindsTo", deps...)
	return workload(u, p, conf.KindService, s.Name, s.Secrets)
}

func box(c *conf.Config, b *conf.Box, p Paths) string {
	u := header(conf.KindBox, b.Name, p, "cyac box "+b.Name)
	u.after("BindsTo", Name(conf.KindNetwork, b.Network))
	var svcs []string
	for _, s := range c.Networks[b.Network].Services {
		svcs = append(svcs, Name(conf.KindService, s))
	}
	u.after("Wants", svcs...)
	return workload(u, p, conf.KindBox, b.Name, nil)
}

func broken(pr conf.Problem, p Paths) string {
	u := header(pr.Kind, pr.Name, p, "cyac "+strings.TrimPrefix(pr.Kind, "cy")+" "+pr.Name+" (invalid, see its status)")
	u.section("Service")
	u.set("Type", "oneshot")
	u.set("ExecStart", fmt.Sprintf("%s -check %s %s", p.Generator, pr.Kind, pr.Name))
	return u.b.String()
}

// Write puts o into dir, which systemd hands the generator empty.
func Write(dir string, o Output) error {
	for name, content := range o.Files {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(content), 0o644); err != nil {
			return err
		}
	}
	for link, target := range o.Symlinks {
		path := filepath.Join(dir, link)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return err
		}
		if err := os.Symlink(target, path); err != nil {
			return err
		}
	}
	return nil
}
